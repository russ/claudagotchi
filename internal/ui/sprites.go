const spriteWidth = 10

// RenderSprite returns the half-block ANSI rendering of the sprite for phase
// at the given animation frame.
func RenderSprite(phase poller.Phase, frame int) string {
	frames, ok := spriteFrames[phase]
	if !ok || len(frames) == 0 {
		return ""
	}
	s := frames[frame%len(frames)]
	pal := palettes[s.palette]
	grid := s.grid
	rows := len(grid)
	if rows == 0 {
		return ""
	}
	cols := len(grid[0])

	var b strings.Builder
	for y := 0; y < rows; y += 2 {
		for x := 0; x < cols; x++ {
			top := grid[y][x]
			bot := 0
			if y+1 < rows {
				bot = grid[y+1][x]
			}
			switch {
			case top == 0 && bot == 0:
				b.WriteByte(' ')
			case top == 0:
				c := pal[bot]
				fmt.Fprintf(&b, "\x1b[38;2;%d;%d;%dm▄\x1b[0m", c.r, c.g, c.b)
			case bot == 0:
				c := pal[top]
				fmt.Fprintf(&b, "\x1b[38;2;%d;%d;%dm▀\x1b[0m", c.r, c.g, c.b)
			default:
				ct := pal[top]
				cb := pal[bot]
				fmt.Fprintf(&b, "\x1b[38;2;%d;%d;%dm\x1b[48;2;%d;%d;%dm▀\x1b[0m",
					ct.r, ct.g, ct.b, cb.r, cb.g, cb.b)
			}
		}
		if y+2 < rows {
			b.WriteByte('\n')
		}
	}
	return b.String()
}
